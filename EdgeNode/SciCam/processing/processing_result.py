from dataclasses import dataclass
from typing import Any


@dataclass(slots=True)
class ProcessingResult:
    """
    Container for all processing results generated by FrameProcessor.
    """

    # ---------------------------------------------------------
    # Images
    # ---------------------------------------------------------

    original: Any
    white_balance: Any
    brown_mask: Any
    histogram_image: Any = None

    # ---------------------------------------------------------
    # Measurements
    # ---------------------------------------------------------

    brown_percentage: float = 0.0

    average_rgb: tuple = (0, 0, 0)

    average_lab: tuple = (0.0, 0.0, 0.0)

    brightness: float = 0.0

    # ---------------------------------------------------------
    # AI / Decision
    # ---------------------------------------------------------

    status: str = "READY"
    fermentation_status: str = "Waiting"
    tea_quality: str = "Waiting"

    confidence: float = 0.0

    # ---------------------------------------------------------
    # Performance
    # ---------------------------------------------------------

    processing_ms: float = 0.0
